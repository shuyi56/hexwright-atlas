const GLYPH_W = 5, GLYPH_H = 7, ADVANCE = 6;
/* the lit pixels of one character, as [x, y] pairs; unknown characters print as a space */
const glyph = ch => { const g = G[ch] || G[' '], out = []; for (let u = 0; u < g.length; u++) if (g[u] === '#') out.push([u % GLYPH_W, (u / GLYPH_W) | 0]); return out; };
const textWidth = s => Math.max(0, s.length * ADVANCE - 1);

export { ADVANCE, GLYPH_H, GLYPH_W, glyph, textWidth };
